function mainZh(zh: string) {
  return zh.split("；")[0].replace(/的$/, "");
}

function displayWord(word: string) {
  return word === "i" ? "I" : word;
}

function articleFor(word: string) {
  return /^[aeiou]/i.test(word) ? "an" : "a";
}

function naturalExample(entry: BasicWord, zh: string): LearningCopy {
  const word = entry.word;
  const shown = displayWord(word);
  const zhMain = mainZh(zh);

  if (entry.category === "action") {
    return {
      zh,
      example: `I will ${word} now.`,
      exampleZh: `我现在会${zhMain}。`,
    };
  }

  if (entry.category === "quality") {
    return {
      zh,
      example: `This seems ${word}.`,
      exampleZh: `这看起来${zhMain}。`,
    };
  }

  if (entry.category === "operator") {
    return {
      zh,
      example: `Use "${shown}" in a short sentence.`,
      exampleZh: `在一个短句里使用“${shown}”。意思是：${zh}。`,
    };
  }

  if (UNCOUNTABLE_WORDS.has(word)) {
    return {
      zh,
      example: `I need ${word}.`,
      exampleZh: `我需要${zhMain}。`,
    };
  }

  if (ABSTRACT_WORDS.has(word) || entry.category === "general") {
    return {
      zh,
      example: `This ${word} is important.`,
      exampleZh: `这个${zhMain}很重要。`,
    };
  }

  if (PLACE_WORDS.has(word)) {
    return {
      zh,
      example: `I am at the ${word}.`,
      exampleZh: `我在${zhMain}。`,
    };
  }

  if (BODY_PART_WORDS.has(word)) {
    return {
      zh,
      example: `The ${word} is important.`,
      exampleZh: `${zhMain}很重要。`,
    };
  }

  if (PERSON_OR_ANIMAL_WORDS.has(word)) {
    return {
      zh,
      example: `I see the ${word}.`,
      exampleZh: `我看见那个${zhMain}。`,
    };
  }

  return {
    zh,
    example: `I have ${articleFor(word)} ${word}.`,
    exampleZh: `我有一个/一件${zhMain}。`,
  };
}

const GENERIC_CATEGORY_COPY: Record<WordCategory, string> = {
  operator: "功能词，用来连接句子关系",
  action: "动作或行为",
  quality: "性质或状态",
  thing: "人、物或具体概念",
  general: "抽象概念或关系",
};

export function getLearningCopy(entry: BasicWord): LearningCopy {
  const word = entry.word;
  if (SPECIAL_EXAMPLES[word]) return SPECIAL_EXAMPLES[word];

  const zh =
    LEARNING_GLOSSES[word] ??
    (entry.zh && entry.zh !== "Basic English 核心词" ? entry.zh : `${word}：${GENERIC_CATEGORY_COPY[entry.category]}`);

  return naturalExample(entry, zh);
}
